namespace QOVETER
{
    /// <summary>
    /// Способ определения расхода воздуха, который греет система отопления.
    ///
    /// <para>Настройка ОБЪЕКТА: методики у заказчиков и смежников расходятся,
    /// и разница в числах велика — на 76-СУЗДАЛ.23 она дала 73% расхождения
    /// с расчётом смежника по этажу.</para>
    /// </summary>
    public enum VentilationMethod
    {
        /// <summary>
        /// По ТЗ, НА КВАРТИРУ: L = max(Σ приток по жилым комнатам,
        /// Σ вытяжка по кухне и санузлам). Нагрузка распределяется по комнатам
        /// с окнами пропорционально площади. Умолчание.
        /// </summary>
        ApartmentNorm = 0,

        /// <summary>
        /// ПОКОМНАТНО по нормам: каждое помещение греет свою норму —
        /// жилая комната приток 3 м³/(ч·м²), кухня и санузел свою вытяжку.
        /// Приближение, которое было до квартирной группировки; им же идёт
        /// сверка со старыми расчётами.
        /// </summary>
        PerRoomNorm = 1,

        /// <summary>
        /// ПО КРАТНОСТИ: L = n · V, где n задаёт инженер
        /// (<see cref="CalculationParameters.AirChangeRatePerHour"/>), V — объём
        /// помещения. Так считают часть смежников; норматив кратность для жилых
        /// комнат не нормирует, поэтому число берётся из проекта, а не из таблицы.
        /// </summary>
        AirChangeRate = 2
    }
}
