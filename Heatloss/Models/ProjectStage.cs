namespace QOVETER
{
    /// <summary>
    /// Стадия проектирования, на которой идёт расчёт. Меняет не формулы, а
    /// УМОЛЧАНИЕ в единственном месте — где исполнение узла инженером не задано
    /// и из равных по числовым признакам таблиц СП 230 надо выбрать одну.
    ///
    /// <para><b>Почему это настройка, а не вечное «худшее».</b> Лист АР с узлами
    /// установки окон появляется только на стадии РД — на стадии П его не
    /// существует ФИЗИЧЕСКИ, и требовать его у инженера бессмысленно. «Худшее из
    /// равных» на П — такая же выдумка, как и «лучшее», только с систематическим
    /// завышением: у оконного узла СФТК между Г.33 и Г.35 разница втрое, и запас
    /// по дому выходил 10–15%, из-за которого сверка с проектировщиком в ±5%
    /// недостижима в принципе.</para>
    /// </summary>
    public enum ProjectStage
    {
        /// <summary>
        /// Проектная документация: чертежей узлов ещё нет. Исполнение не задано —
        /// берётся ТИПОВОЕ: середина сетки равных таблиц СП 230 по потерям,
        /// с пометкой в журнале и отчёте. Умолчание.
        /// </summary>
        P = 0,

        /// <summary>
        /// Рабочая документация: узлы есть в альбоме. Исполнение задаётся в файле
        /// объекта &lt;модель&gt;.QOVETER-узлы.json; что не задано — берётся
        /// ХУДШЕЕ из равных («в запас»), и сводка прогона это называет.
        /// </summary>
        RD = 1
    }
}
