namespace QOVETER
{
    /// <summary>
    /// Откуда берутся сопротивления теплопередаче наружных ограждений.
    ///
    /// <para><b>Зачем режим «по нормируемому».</b> Модель АР на стадии расчёта
    /// отопления часто неактуальна: слои, материалы и фасадная система в ней
    /// устарели или не нарисованы. Разбирать такой пирог по слоям и достраивать
    /// узлы СП 230 — считать дом, которого нет. Заявка проектировщиков ОВ
    /// 2026-10-15: «задавать R вручную или считать по нормируемому». В этом
    /// режиме из модели берутся только площади, ориентация и соседство, а R —
    /// из СП 50.13330.2024 таблица 3 по ГСОП площадки (для жилых значения
    /// совпадают с редакцией 2012), с понижающим m_p по п. 5.2.</para>
    /// </summary>
    public enum ResistanceSource
    {
        /// <summary>
        /// По модели: слои, λ из СП 50 прил. Т, приведение по узлам СП 230,
        /// нормируемое R — только нижней границей для фасада. Умолчание.
        /// </summary>
        Model = 0,

        /// <summary>
        /// По нормируемому: стены (включая стены в грунте), покрытие, перекрытие
        /// над подвалом и пол по грунту к НАРУЖНОМУ воздуху — R по СП 50 табл. 3
        /// (графы 3–5) × m_p, либо R, заданное инженером. Окна — ручное R, иначе
        /// модель (ответ ОВ 2026-10-15). Слои модели и узлы СП 230 не участвуют:
        /// табличное R уже приведённое. Ограждения к лоджиям, лестницам, шахтам
        /// и двери — по модели.
        /// </summary>
        Normative = 1
    }

    /// <summary>
    /// R объекта, заданные инженером одним числом на вид ограждения, м²·°С/Вт —
    /// с сопротивлениями теплоотдаче, как в таблице 3 СП 50. null — не задано.
    ///
    /// <para>Ответ проектировщиков ОВ 2026-10-15: «одно R на все наружные стены,
    /// одно на окна, одно на кровлю, одно на пол». Детализация по типам стен
    /// живёт отдельно, в <c>wall_types.json</c>, и в этом режиме не участвует.</para>
    /// </summary>
    public class ManualResistances
    {
        public double? Wall { get; set; }
        public double? Window { get; set; }
        public double? Roof { get; set; }
        public double? Floor { get; set; }

        /// <summary>Тот же сторож, что у ручного R по типам: вне 0,1…20 — описка или единицы.</summary>
        public static bool IsPlausible(double r) => r >= 0.1 && r <= 20;

        /// <summary>Имя первого заданного значения вне диапазона; null — всё в порядке.</summary>
        public string FirstImplausible()
        {
            if (Wall.HasValue   && !IsPlausible(Wall.Value))   return "стен";
            if (Window.HasValue && !IsPlausible(Window.Value)) return "окон";
            if (Roof.HasValue   && !IsPlausible(Roof.Value))   return "кровли";
            if (Floor.HasValue  && !IsPlausible(Floor.Value))  return "пола";
            return null;
        }
    }
}
