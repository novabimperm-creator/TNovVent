using QOVETER.Models;
using QOVETER.Services;
using System.Collections.Generic;

namespace QOVETER
{
    public class CalculationParameters
    {
        // Температурные параметры
        public double InternalTemperature { get; set; } = 20.0;
        public double ExternalTemperature { get; set; } = -25.0;
        public double FloorTemperature { get; set; } = 5.0; // Для пола первого этажа

        // Параметры заселенности
        public double OccupancyDensity { get; set; } = 20.0; // м²/чел

        // Нормы воздухообмена живут в ThermalConstants со ссылками на пункты ТЗ и СП;
        // здешние копии AirExchangePerPerson/AirExchangePerArea не читал никто —
        // второй набор норм рядом с первым опаснее, чем его отсутствие.

        /// <summary>
        /// В здании газовые плиты (вытяжка кухни 100 м³/ч вместо 60).
        /// Свойство здания, а не помещения: раньше газ определялся поиском слова «газ»
        /// в имени комнаты — в реальных моделях так помещения не называют.
        /// ТЗ оговаривает только электрическую плиту, поэтому по умолчанию false.
        /// </summary>
        public bool GasStoves { get; set; } = false;

        /// <summary>
        /// Считать воздухообмен НА КВАРТИРУ, как требует ТЗ:
        /// L = max(Σ норма притока по жилым комнатам, Σ норма вытяжки по кухне и санузлам),
        /// и полученная нагрузка распределяется по комнатам квартиры, ИМЕЮЩИМ ОКНА,
        /// пропорционально их площади.
        ///
        /// Помещения без номера квартиры (общедомовые — лестницы, лифтовые холлы,
        /// внеквартирные коридоры) считаются покомнатно независимо от флага.
        /// Выключение возвращает старое покомнатное приближение — оно оставлено
        /// для сверки с расчётами, сделанными до появления квартирной группировки.
        /// </summary>
        public bool UseApartmentGrouping
        {
            get { return Ventilation == VentilationMethod.ApartmentNorm; }
            set { Ventilation = value ? VentilationMethod.ApartmentNorm : VentilationMethod.PerRoomNorm; }
        }

        /// <summary>
        /// Как считается воздухообмен. НАСТРОЙКА ОБЪЕКТА, а не константа программы:
        /// у разных заказчиков и разных смежников методики расходятся, и плагин
        /// обязан уметь посчитать так, как считает объект.
        ///
        /// <para><b>Цена вопроса измерена</b> на 76-СУЗДАЛ.23 (прогон 2026-08-19 17:12):
        /// кухни по квартирной норме ТЗ получают ~48 м³/ч и дают 8 362 Вт на этаже,
        /// а в расчёте смежника (Rti.exe, файл «крат 3») — около 70 м³/ч и 11 055 Вт.
        /// Разница −24,4% на кухнях, и это <b>73% всего оставшегося расхождения
        /// по этажу</b>. Ни температуры, ни ограждения к ней отношения не имеют.</para>
        ///
        /// <para>Задаётся в файле объекта <c>&lt;модель&gt;.QOVETER-узлы.json</c> —
        /// там же, где исполнение узлов, и по той же причине: свойство объекта,
        /// а не программы.</para>
        /// </summary>
        public VentilationMethod Ventilation { get; set; } = VentilationMethod.ApartmentNorm;

        /// <summary>
        /// Кратность воздухообмена, 1/ч — для <see cref="VentilationMethod.AirChangeRate"/>.
        /// Ноль означает «не задана»: считать по кратности при незаданном числе
        /// нельзя, движок откатится к квартирной норме и скажет об этом.
        ///
        /// <para>Умолчания у кратности НЕТ намеренно. Норматив даёт нормируемый
        /// РАСХОД (приток 3 м³/(ч·м²) по жилым, вытяжка кухни 60/90, санузла 25/50),
        /// а кратность — это решение конкретного проекта. Подставить сюда число
        /// от себя значило бы выдать его за норму.</para>
        /// </summary>
        public double AirChangeRatePerHour { get; set; } = 0;

        /// <summary>
        /// Имя параметра помещения, где лежит номер квартиры. Пусто — плагин
        /// перебирает типовые имена и «Комментарии».
        /// </summary>
        public string ApartmentParameterName { get; set; } = "";

        /// <summary>
        /// ВСЕ собранные помещения, а не только выбранные для расчёта.
        ///
        /// Нужны для теплового баланса неотапливаемых объёмов: лоджия снята
        /// с расчёта по умолчанию, в список движка не попадает — а её остекление
        /// и есть холодная сторона баланса стены «кухня — лоджия». Пусто —
        /// температуры берутся из таблицы, как было до 2026-08-13; на этом
        /// держится неизменность golden-фикстур, где соседних помещений нет.
        ///
        /// Тот же приём, что у <see cref="ApartmentComposition"/>: состав квартиры
        /// тоже нельзя восстановить по одному лишь выбранному подмножеству.
        /// </summary>
        public List<RoomData> AllRooms { get; set; }

        /// <summary>
        /// Способ получения приведённого сопротивления наружных стен.
        ///
        /// <para><b>С 2026-08-19 включено по умолчанию.</b> Норматив требует
        /// R ПРИВЕДЁННОЕ (СП 50.13330.2012 п. 5.1), проектировщик считает по нему,
        /// а слоёный пирог даёт R УСЛОВНОЕ — оно всегда выше, то есть выключенный
        /// режим систематически ЗАНИЖАЛ теплопотери. На 76-СУЗДАЛ.23 это часть
        /// недолёта −18,4% по итогу 2026-08-17.</para>
        ///
        /// <para><b>Почему теперь можно.</b> Ψ берутся из встроенного каталога
        /// СП 230.1325800.2015 (81 таблица приложения Г, ресурс
        /// <c>Resources/SP230Bridges.json</c>), а не из оценок «из коробки».
        /// Предварительные значения <see cref="ThermalBridgeCatalog"/> в итог
        /// БОЛЬШЕ НЕ ИДУТ: узел, для которого таблицы СП нет, пропускается
        /// и печатается в сводке прогона. Ровно то, чего требовало прежнее
        /// умолчание, — только вместо выключения всего расчёта выключается
        /// один неподтверждённый узел.</para>
        ///
        /// <para>Свои Ψ — в <c>%APPDATA%\QOVETER\thermal_bridges.json</c>
        /// с <c>IsVerified = true</c>; они главнее пропуска, но ниже таблиц СП.
        /// Режим <see cref="ReducedResistanceMode.HomogeneityFactor"/> остаётся
        /// для случая, когда инженер задаёт r одним числом.</para>
        /// </summary>
        public ReducedResistanceMode ReducedResistance { get; set; } = ReducedResistanceMode.Catalog;

        /// <summary>
        /// Коэффициент теплотехнической однородности r для режима
        /// <see cref="ReducedResistanceMode.HomogeneityFactor"/>. Типовой диапазон
        /// для многослойных стен — 0.7…0.92; чем ниже, тем больше доля мостиков.
        /// </summary>
        public double HomogeneityFactor { get; set; } = 0.85;

        /// <summary>
        /// Исполнение узлов, которое из модели Revit не вытащить: толщина оконной рамы,
        /// зуб (четверть), нахлёст утеплителя на раму, утепление плиты цокольного
        /// перекрытия. По этим признакам выбирается таблица СП 230.
        ///
        /// Значения по умолчанию подобраны «в запас» — то есть в сторону БОЛЬШИХ потерь:
        /// без зуба и без нахлёста узел холоднее, утепление плиты взято минимальным
        /// из сетки СП. Инженер уточняет их по своему проекту.
        /// Толщина рамы 80 мм, а не 60: СП прямо пишет, что рама 60 мм и тоньше
        /// в жилых домах большинства климатических зон недопустима без дополнительного
        /// утепления узла.
        /// </summary>
        public BridgeSelectors NodeDetails { get; set; } = new BridgeSelectors
        {
            FrameMm = 80,
            NotchMm = 0,
            OverlapMm = 0,
            SlabInsulationR = 1.88,
            SlabThicknessMm = 210,
            // 3/1 — по тексту СП «типовое для современного строительства».
            // Ноль (без перфорации) в качестве значения по умолчанию не берём:
            // СП прямо называет такие узлы недопустимыми в современных конструкциях
            // и приводит их только как базу интерполяции.
            SlabPerforationRatio = 3,
            // Без дополнительного утепления парапета — худший вариант из сетки СП.
            // По примечанию к таблицам Г.41–Г.49 влияние этого утепления слабое,
            // так что цена ошибки здесь мала.
            ParapetInsulationMm = 0,

            // ИСПОЛНЕНИЕ узла не задано: у части таблиц СП числовые признаки
            // совпадают полностью и различаются только конструктивом — обычная
            // перфорация против несущих теплоизоляционных элементов (Г.6 и Г.10),
            // положение оконной рамы относительно утеплителя (Г.33–Г.35, разница
            // втрое). Пока здесь пусто, из равных берётся ХУДШЕЕ по потерям, и
            // в отчёт идёт пометка «исполнение не задано, принято … — в запас».
            // Инженер, знающий свой узел, ставит сюда его имя: «ThermalInsert»,
            // «FrameAtInsulation», «TwoLayerInsulationWithAirGap» и т. п.
            Execution = null
        };

        // Коэффициенты
        public bool UseSafetyFactor { get; set; } = true;
        public double SafetyFactor { get; set; } = 1.2;
        public bool DetailedCalculation { get; set; } = true;

        /// <summary>
        /// Учитывать ли бытовые тепловыделения (Q_вн) при расчёте Q_total.
        /// По ТЗ: Q_расч = Q_огр + Q_инф/вент − Q_вн. По умолчанию false —
        /// чтобы не занижать тепловую нагрузку на систему отопления.
        /// </summary>
        public bool SubtractInternalHeatGains { get; set; } = false;

        // Географические параметры
        public string SelectedCity { get; set; } = "Москва";
        public double CityTemperature { get; set; } = -25.0;
        public string Region { get; set; } = "Центральный";

        // Параметры здания. Высота здания живёт в BuildingParameters.TotalHeight —
        // от неё считается β наружной двери; здешняя копия BuildingHeight не читалась
        // нигде, и две высоты в одном объекте параметров расходились бы молча.
        public BuildingParameters BuildingParams { get; set; } = new BuildingParameters();

        // Выбранные помещения
        public List<RoomData> SelectedRooms { get; set; } = new List<RoomData>();

        /// <summary>
        /// ПОЛНЫЙ состав помещений модели — для нормирования воздухообмена квартиры.
        ///
        /// Зачем отдельно от <see cref="SelectedRooms"/>: по ТЗ норма квартиры это
        /// <c>L = max(Σ приток по жилым, Σ вытяжка по кухне и санузлам)</c>, и она
        /// определяется СОСТАВОМ КВАРТИРЫ, а не тем, какие строки инженер оставил
        /// в отчёте. Пока сюда ничего не передавали, норма считалась по выбранным
        /// помещениям: стоило снять галочку с санузла — и Σ вытяжка падала на
        /// 50 м³/ч, L уменьшалась, а жилые комнаты той же квартиры получали
        /// МЕНЬШЕ мощности. Инженер думал, что убирает строку из отчёта, а менял
        /// воздушный баланс квартиры.
        ///
        /// Пусто — норма считается по переданным на расчёт помещениям (прежнее
        /// поведение; так работают тесты на синтетике и golden-фикстура).
        /// </summary>
        public List<RoomData> ApartmentComposition { get; set; }

        /// <summary>
        /// Что именно охватывает расчёт — идёт в подпись итоговой строки.
        /// Раньше итог всегда назывался «ИТОГО ПО ЗДАНИЮ», хотя суммировал только
        /// ВЫБРАННЫЕ помещения: стоило выбрать в списке конкретный этаж, и его сумма
        /// подавалась как итог по зданию. В отчёт такие числа уходили с той же подписью.
        /// </summary>
        public string ScopeName { get; set; } = "ПО ЗДАНИЮ";

        /// <summary>
        /// Расчётные температуры по типам помещений (ручное задание через UI).
        /// Если null — применяются значения по ГОСТ 30494-2011.
        /// </summary>
        public RoomTypeTemperatures RoomTemperatures { get; set; } = new RoomTypeTemperatures();

        // Конструктор
        public CalculationParameters()
        {
            // Значения по умолчанию
        }

        // Метод для проверки корректности параметров
        public bool Validate(out string errorMessage)
        {
            errorMessage = "";

            if (InternalTemperature <= ExternalTemperature)
            {
                errorMessage = "Внутренняя температура должна быть выше наружной";
                return false;
            }

            if (OccupancyDensity <= 0)
            {
                errorMessage = "Плотность заселения должна быть положительной";
                return false;
            }

            if (SafetyFactor <= 0)
            {
                errorMessage = "Коэффициент запаса должен быть положительным";
                return false;
            }

            return true;
        }

        // Метод для получения описания параметров
        public string GetDescription()
        {
            return $"tв = {InternalTemperature}°C, tн = {ExternalTemperature}°C, " +
                   $"Плотность: {OccupancyDensity} м²/чел, Город: {SelectedCity}";
        }
    }
}