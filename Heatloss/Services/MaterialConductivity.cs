        /// <summary>
        /// Условия эксплуатации ограждающих конструкций по СП 50.13330.2012
        /// таблица 2. Определяются влажностным режимом помещения (таблица 1)
        /// и зоной влажности района строительства (приложение В).
        /// </summary>
        public enum OperatingCondition
        {
            /// <summary>Сухой режим в сухой либо нормальной зоне влажности.</summary>
            A,

            /// <summary>Нормальный режим в нормальной зоне и всё, что влажнее. Умолчание.</summary>
            B
        }

        /// <summary>
        /// Условия по умолчанию — Б: нормальный влажностный режим жилого дома
        /// в нормальной зоне влажности (Ярославль, Москва, большая часть ЦФО).
        /// λ_Б ≥ λ_А, поэтому умолчание работает в запас.
        /// </summary>
        public const OperatingCondition DefaultCondition = OperatingCondition.B;

        /// <summary>
        /// Распознан ли материал по имени типа или материала. Возвращает запись
        /// каталога вместе со ссылкой на позицию таблицы СП.
        /// </summary>
        public static bool TryResolve(string name, out MaterialEntry entry)
        {
            entry = null;
            string normalized = Normalize(name);
            if (normalized.Length == 0) return false;

            // Порядок в каталоге значим: утеплитель проверяется раньше штукатурки
            // и раньше фасада, ячеистый бетон — раньше тяжёлого. Разбор идёт
            // сверху вниз, первое совпадение выигрывает.
            entry = Catalog.FirstOrDefault(e => e.Keywords.Any(k => normalized.Contains(k)));
            return entry != null;
        }

        /// <summary>
        /// λ материала, Вт/(м·К), для заданных условий эксплуатации.
        /// 0 — материал не распознан.
        /// </summary>
        public static double Resolve(string name, OperatingCondition condition = DefaultCondition)
        {
            MaterialEntry entry;
            return TryResolve(name, out entry) ? entry.Lambda(condition) : 0;
        }

        private static string Normalize(string value)
        {
            // Пробелы внутри имени убираются: модель пишет и «Силикатныйблок250»,
            // и «Силикатный блок 250», и «Утеплитель НГ 140» — для поиска
            // по подстроке это должно быть одно и то же.
            return (value ?? "").ToLowerInvariant().Replace(" ", "").Replace("-", "");
        }

