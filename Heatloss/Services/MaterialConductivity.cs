    /// Теплопроводность материала по НОРМАТИВУ, когда её нет в модели.
    ///
    /// <para><b>Зачем этот класс существует.</b> На 76-СУЗДАЛ.23 по данным модели
    /// считается 30 м² из 5 369 (0,6%). При этом фасадная система в модели НАРИСОВАНА
