        /// <summary>
        /// Запись каталога: материал, его λ при обоих условиях эксплуатации
        /// и ссылка на позицию таблицы норматива.
        /// </summary>
        public class MaterialEntry
        {
            public MaterialEntry(string[] keywords, string material,
                                 double lambdaA, double lambdaB,
                                 string spRow, string note = null)
            {
                Keywords = keywords;
                Material = material;
                LambdaA  = lambdaA;
                LambdaB  = lambdaB;
                SpRow    = spRow;
                Note     = note ?? "";
            }

            /// <summary>Подстроки имени типа или материала, по которым узнаётся запись.</summary>
            public string[] Keywords { get; }

            /// <summary>Наименование материала так, как оно стоит в таблице СП.</summary>
            public string Material { get; }

            /// <summary>λ при условиях эксплуатации А, Вт/(м·К).</summary>
            public double LambdaA { get; }

            /// <summary>λ при условиях эксплуатации Б, Вт/(м·К).</summary>
            public double LambdaB { get; }

            /// <summary>Позиция таблицы норматива — идёт в журнал и в отчёт.</summary>
            public string SpRow { get; }

            /// <summary>Чем обоснован выбор строки, если в таблице их несколько.</summary>
            public string Note { get; }

            public double Lambda(OperatingCondition condition)
            {
                return condition == OperatingCondition.A ? LambdaA : LambdaB;
            }

            /// <summary>Строка для журнала и отчёта: материал, λ и откуда взято.</summary>
            public string Describe(OperatingCondition condition)
            {
                return $"{Material}, λ_{(condition == OperatingCondition.A ? "А" : "Б")} = " +
                       $"{Lambda(condition):F3} ({SpRow})";
            }
        }
