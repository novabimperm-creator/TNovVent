    /// Толщина при этом известна точно: её даёт <c>Wall.Width</c>.</para>
    ///
    /// <para><b>Почему это не «выдуманное число».</b> λ здесь не подбирается под
    /// результат: материал распознаётся по имени типа («Наруж стена
    /// Силикатныйблок250», «Фасад Утеплитель НГ 140 под штукатурку»), а значение
    /// берётся ИЗ ТАБЛИЦЫ СП 50.13330.2012 Приложение Т, выписанной построчно
    /// из текста норматива. У каждой записи стоит номер позиции таблицы, и он
    /// печатается в журнале и в отчёте — так же, как номер таблицы у Ψ по СП 230.
    /// Это ровно то, что делает проектировщик, когда в модели нет теплотехники.</para>
    ///
    /// <para><b>Условия эксплуатации — Б.</b> СП 50.13330.2012 п. 4.4 и таблица 2:
    /// при нормальном влажностном режиме помещения и нормальной зоне влажности
    /// района строительства (приложение В) принимаются условия <b>Б</b>. Для
    /// сухого режима в сухой зоне были бы условия А; λ_Б всегда больше λ_А,
    /// то есть выбор Б — оценка В ЗАПАС.</para>
    ///
    /// <para><b>Приоритет ниже данных модели и ручного ввода.</b> Порядок в
    /// <see cref="WallThermalCalculator"/>: слои модели → аналитическое R →
    /// параметр стены → <c>wall_types.json</c> → <b>этот каталог</b> → типовое U.
    /// Проектное R из раздела АР главнее нормативной таблицы, а данные модели
    /// главнее обоих.</para>
    /// </summary>
    public static class MaterialConductivity
