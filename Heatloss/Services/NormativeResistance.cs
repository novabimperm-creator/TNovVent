using System;

namespace QOVETER.Services
{
    /// <summary>
    /// Нормируемое (базовое требуемое) сопротивление теплопередаче ограждающих
    /// конструкций — СП 50.13330.2012, п. 5.2 и таблица 3.
    ///
    /// <para><b>Зачем это в расчёте теплопотерь.</b> Модель не обязана содержать
    /// теплотехнику и обычно её не содержит. Хуже: на 76-СУЗДАЛ.23 фасадная
    /// система местами вообще не смоделирована — сплошная проба показывает, что
    /// перед монолитом 200 мм на 70 см НЕТ НИЧЕГО. Считать такую стену голым
    /// бетоном (U = 3,73) — значит выдать за расчёт число, которого в природе
    /// нет: наружная стена жилого дома в Ярославле при −29 °C столько потерь
    /// не даёт и по нормативу дать не может.</para>
    ///
    /// <para><b>Правило.</b> Ограждение, выходящее НА НАРУЖНЫЙ ВОЗДУХ, не может
    /// иметь сопротивление ниже базового требуемого: здание, спроектированное
    /// иначе, не прошло бы экспертизу. Если данные модели дают меньше — данных
    /// нет, а не стена такая. Тогда принимается нормируемое значение, и это
    /// ЗАЯВЛЯЕТСЯ в отчёте отдельной строкой со ссылкой на таблицу.</para>
    ///
    /// <para><b>Где это НЕ применяется.</b> К внутренним ограждениям — к шахте,
    /// лестнице, лоджии, соседней квартире. Там норматив требований не
    /// предъявляет, а конструкция действительно бывает неутеплённой, и
    /// подстановка «нормы» завысила бы сопротивление втрое.</para>
    ///
    /// <para>Класс намеренно не знает про Revit: правило нормативное и обязано
    /// проверяться автотестами.</para>
    /// </summary>
    public static class NormativeResistance
    {
        /// <summary>
        /// Градусо-сутки отопительного периода, °С·сут/год.
        /// СП 50.13330.2012 формула (5.2): ГСОП = (t_в − t_от)·z_от.
        /// </summary>
        /// <param name="indoorTemp">Расчётная температура внутреннего воздуха, °C.</param>
        /// <param name="heatingPeriodTemp">Средняя температура отопительного периода, °C.</param>
        /// <param name="heatingPeriodDays">Продолжительность отопительного периода, сут.</param>
        public static double DegreeDays(double indoorTemp, double heatingPeriodTemp, int heatingPeriodDays)
        {
            if (heatingPeriodDays <= 0) return 0;
            return (indoorTemp - heatingPeriodTemp) * heatingPeriodDays;
        }

        /// <summary>Вид ограждающей конструкции — задаёт столбец таблицы 3.</summary>
        public enum Enclosure
        {
            Wall,
            Roof,
            FloorOverUnheated,
            Window
        }

        /// <summary>
        /// Базовое требуемое сопротивление теплопередаче, м²·°С/Вт.
        /// СП 50.13330.2012 таблица 3, строка 1.1 «Жилые, гостиницы и общежития»:
        /// R = a·ГСОП + b.
        ///
        /// <para>Коэффициенты выписаны из текста норматива:
        /// стены a = 0,00035, b = 1,4; покрытия a = 0,0005, b = 2,2;
        /// перекрытия над неотапливаемыми подпольями a = 0,00045, b = 1,9;
        /// светопрозрачные a = 0,000025, b = 0,25. Проверка по базовым значениям
        /// той же таблицы: при ГСОП = 4000 стены дают 2,8 — совпадает.</para>
        /// </summary>
        public static double Required(Enclosure enclosure, double degreeDays)
        {
            if (degreeDays <= 0) return 0;

            // ⚠ У СВЕТОПРОЗРАЧНЫХ конструкций в строке коэффициентов стоят
            // ПРОЧЕРКИ — и a, и b. Норматив там формулы не даёт вовсе, базовые
            // значения берутся только из самой таблицы. Коэффициенты 0,000025
            // и 0,25, стоящие в той же строке, относятся к ФОНАРЯМ, соседнему
            // столбцу. Подставить их окну — ошибка почти вдвое: при ГСОП 4000
            // формула даёт 0,35, а таблица требует 0,63.
            if (enclosure == Enclosure.Window)
                return InterpolateWindow(degreeDays);

            double a, b;
            switch (enclosure)
            {
                case Enclosure.Roof:               a = 0.0005;   b = 2.2;  break;
                case Enclosure.FloorOverUnheated:  a = 0.00045;  b = 1.9;  break;
                default:                           a = 0.00035;  b = 1.4;  break;
            }

            return a * degreeDays + b;
        }

        /// <summary>
        /// Базовые значения для светопрозрачных конструкций (кроме фонарей),
        /// СП 50.13330.2012 таблица 3, строка 1.1. Между узлами сетки —
        /// линейная интерполяция, за её пределами значение зажимается по краю:
        /// экстраполяции норматив не даёт. Та же дисциплина, что в каталоге СП 230.
        /// </summary>
        private static double InterpolateWindow(double degreeDays)
        {
            double[] grid   = { 2000, 4000, 6000, 8000, 10000, 12000 };
            double[] values = { 0.49, 0.63, 0.73, 0.75,  0.77,  0.80 };

            if (degreeDays <= grid[0]) return values[0];
            if (degreeDays >= grid[grid.Length - 1]) return values[values.Length - 1];

            for (int i = 1; i < grid.Length; i++)
            {
                if (degreeDays > grid[i]) continue;
                double t = (degreeDays - grid[i - 1]) / (grid[i] - grid[i - 1]);
                return values[i - 1] + t * (values[i] - values[i - 1]);
            }

            return values[values.Length - 1];
        }

        /// <summary>
        /// Сопротивление ограждения к НАРУЖНОМУ ВОЗДУХУ, не меньшее нормативного.
        /// Возвращает <paramref name="modelR"/>, если данные модели норматив
        /// удовлетворяют, иначе нормируемое значение.
        ///
        /// <para><b>Только вверх и только для наружного воздуха.</b> Стена лучше
        /// нормы — это проектное решение, и занижать его нельзя. Стена хуже нормы
        /// на фасаде — это пробел в модели.</para>
        /// </summary>
        public static double ApplyFloor(double modelR, Enclosure enclosure, double degreeDays,
                                        out bool raised)
        {
            raised = false;
            double required = Required(enclosure, degreeDays);
            if (required <= 0 || modelR >= required) return modelR;

            raised = true;
            return required;
        }
    }
}
