using System.Text.RegularExpressions;

namespace QOVETER.Services
{
    /// <summary>
    /// Распознавание конструкции по ИМЕНИ типа или материала.
    ///
    /// <para>Вынесено отдельно и без Revit API по двум причинам. Первая: эти правила
    /// решают нормативный вопрос (что войдёт в сопротивление ограждения), поэтому
    /// обязаны проверяться автотестами. Вторая: ошибка здесь бесшумна и стоит
    /// дорого в обе стороны — измерено на 76-СУЗДАЛ.23 2026-08-12:</para>
    ///
    /// <list type="bullet">
    /// <item>приняли прослойку за утеплитель — «Фасад Зазор225» дал R = 9,17
    /// (воздух по λ ≈ 0,024), стена вышла теплее любого утеплителя;</item>
    /// <item>приняли утеплитель за прослойку — подстрока «вент» выбросила
    /// «Фасад Утеплитель 90+50 под вентфасад», 150 срабатываний из 208
    /// за прогон, и вся правка про сборку стены не дала ничего.</item>
    /// </list>
    /// </summary>
    public static class LayerNaming
    {
        /// <summary>
        /// Слой воздуха: замкнутая или вентилируемая прослойка.
        ///
        /// Считать её по λ нельзя: воздух передаёт теплоту конвекцией и излучением,
        /// поэтому СП 50.13330 даёт замкнутым прослойкам ТАБЛИЧНЫЕ сопротивления,
        /// а слои за вентилируемой не учитывает вовсе.
        /// </summary>
        public static bool IsAirLayer(string materialName)
        {
            string name = Normalize(materialName);
            if (name.Length == 0) return false;
            if (IsInsulation(name)) return false;

            return name.Contains("воздух") ||
                   name.Contains("воздуш") ||
                   name.Contains("зазор") ||
                   name.Contains("прослойк") ||
                   name == "air" ||
                   name.StartsWith("air ") ||
                   name.Contains(" air");
        }

        /// <summary>
        /// Вентилируемая прослойка фасадной системы, стоящая отдельным элементом.
        /// На ней сборка ограждения обрывается: то, что снаружи прослойки,
        /// по СП 50.13330 в сопротивление не входит.
        /// </summary>
        public static bool IsVentilatedFacadeLayer(string typeName)
        {
            string name = Normalize(typeName);
            if (name.Length == 0) return false;
            if (IsInsulation(name)) return false;

            // Признаки те же, что у материала-воздуха, плюс имя подсистемы:
            // «Фасад навесной вент 85 White Hills 25» — это зазор 85 мм, что
            // видно по совпадению R с «Фасад Зазор85» (оба 3,57).
            return IsAirLayer(name) || name.Contains("навесной вент");
        }

        /// <summary>
        /// Стена шахты (вентиляционной, лифтовой). Самостоятельная конструкция
        /// внутри здания, а не слой перед несущей стеной.
        /// </summary>
        public static bool IsShaft(string typeName)
        {
            return Normalize(typeName).Contains("шахт");
        }

        /// <summary>
        /// Утеплитель. Проверяется ПЕРВЫМ везде: утеплитель называют по системе,
        /// в которую он входит («под вентфасад», «под штукатурку»), и любой поиск
        /// по «вент» без этой проверки выбрасывает именно его.
        /// </summary>
        private static bool IsInsulation(string normalizedName)
        {
            return normalizedName.Contains("утеплит") ||
                   normalizedName.Contains("пеноплэкс") ||
                   normalizedName.Contains("пенополист") ||
                   normalizedName.Contains("минват") ||
                   normalizedName.Contains("минеральная вата") ||
                   normalizedName.Contains("каменная вата") ||
                   AbbreviatedInsulation.IsMatch(normalizedName);
        }

        /// <summary>
        /// Сокращённая запись утеплителя с толщиной: «Фасад Ут140 Хризлист20»,
        /// «Наруж стена Ут50», «Кровля Ут100». Модель пишет её наравне с полным
        /// словом, и без этого шаблона такие слои не опознаются утеплителем.
        ///
        /// <para>Цифра в шаблоне обязательна: голое «ут» — слишком частый
        /// обрывок, чтобы что-то решать. Проверено, что шаблон не задевает
        /// «Штук15», «Штукат10» и «Аквапанель10»: в них перед цифрой нет «ут».</para>
        /// </summary>
        private static readonly Regex AbbreviatedInsulation = new Regex(@"ут\s*\d", RegexOptions.Compiled);

        /// <summary>
        /// Слой фасадной системы или утеплитель — то, что заведомо НЕ перегородка.
        ///
        /// <para><b>Зачем.</b> Отбор слоёв перед несущей стеной отбрасывает
        /// перегородки, и признаком перегородки служит в том числе функция стены
        /// <c>Interior</c>. Но фасадные слои в моделях рисуют именно так: они
        /// не несущие и не «наружная стена» в понимании Revit. В итоге настоящий
        /// утеплитель выбрасывался молча.</para>
        ///
        /// <para><b>Улика с 76-СУЗДАЛ.23, прогон 2026-08-17:</b> из 216 слоёв,
        /// отброшенных как перегородка, 109 — утеплитель и фасад:
        /// «Отделка Утеплитель100 Штук10» (40), «Фасад ГИх2 Пеноплэкс100
        /// Мембрана» (33), «Фасад Ут140 Хризлист20 Праймер+ГИ2» (10),
        /// «Наруж стена ЯчБлок 90» (10) и другие. Остальные 107 —
        /// настоящие перегородки («Перегородка Силикатная пазогребневая 70/115»,
        /// «Перегородка Кирп120 рядовой»), и их отбраковка верна.</para>
        ///
        /// <para><b>Кровля исключена намеренно.</b> «Кровля Ут100 Хризлист20» —
        /// утеплитель покрытия, а не стены; попасть в сборку стены он может
        /// только у парапета, и там это чужая конструкция.</para>
        /// </summary>
        public static bool IsFacadeOrInsulationLayer(string typeName)
        {
            string name = Normalize(typeName);
            if (name.Length == 0) return false;
            if (name.Contains("кровл")) return false;

            return IsInsulation(name) ||
                   name.Contains("фасад") ||
                   name.Contains("наруж");
        }

        private static string Normalize(string value)
        {
            return (value ?? "").Trim().ToLowerInvariant();
        }
    }
}
